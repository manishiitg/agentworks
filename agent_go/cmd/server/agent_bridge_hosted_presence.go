// Only the authenticated chat-view lifecycle supplies this signal. Provider
// processes, internal event subscribers and a device-wide stream are not views.
var hostedChatViews = struct {
	sync.Mutex
	counts map[hostedChatViewKey]int
}{counts: map[hostedChatViewKey]int{}}

type hostedChatViewKey struct {
	owner   string
	binding hostedBridgeBinding
}

func observeHostedChatView(owner string, binding hostedBridgeBinding) func() {
	if owner == "" || binding.Chat == "" {
		return func() {}
	}
	key := hostedChatViewKey{owner, binding}
	hostedChatViews.Lock()
	hostedChatViews.counts[key]++
	hostedChatViews.Unlock()
	log.Printf("[AGENTBRIDGE] event=chat_view owner=%s chat=%s action=opened", owner, binding.Chat)
	var once sync.Once
	return func() {
		once.Do(func() {
			hostedChatViews.Lock()
			hostedChatViews.counts[key]--
			if hostedChatViews.counts[key] <= 0 {
				delete(hostedChatViews.counts, key)
			}
			hostedChatViews.Unlock()
			log.Printf("[AGENTBRIDGE] event=chat_view owner=%s chat=%s action=closed", owner, binding.Chat)
		})
	}
}

func hostedChatViewed(owner string, binding hostedBridgeBinding) bool {
	hostedChatViews.Lock()
	defer hostedChatViews.Unlock()
	return hostedChatViews.counts[hostedChatViewKey{owner, binding}] > 0
}

func hostedDirectoryTab(tab crewOwnerChat) bool {
	// The default agent is a role, even when its saved identity still contains a
	// login or Crew name; the authenticated owner view is its only separate row.
	// A saved/autogenerated conversation title is not an explicit agent name.
	name := strings.TrimSpace(tab.Identity.Name)
	return !tab.Record.IsDefaultAgent && !tab.Identity.GeneratedName && name != "" || hostedChatViewed(tab.OwnerID, hostedBindingForRecord(tab.Record))
}

func hostedAgentDirectoryVisible(ctx context.Context, a namedMessageAgent) bool {
	if a.Hosted == nil {
		return true
	}
	record, err := currentHostedBridgeRecord(ctx, a.UserID, *a.Hosted)
	if err != nil {
		return false
	}
	identities, err := defaultProductConversationRegistryStore().agentIdentities(ctx, a.UserID, a.Hosted.Profile, a.Hosted.Project)
	return err == nil && hostedDirectoryTab(crewOwnerChat{Record: record, Identity: identities[record.ConversationKey], OwnerID: a.UserID})
}

func hostedAgentViewed(a namedMessageAgent) bool {
	if a.Hosted == nil {
		return false
	}
	return hostedChatViewed(a.UserID, *a.Hosted)
}

func hostedBindingForRecord(record ProductConversationRecord) hostedBridgeBinding {
	return hostedBridgeBinding{Profile: record.ProfileID, Project: crewResourceProjectID(record.ConversationKey), Chat: record.ConversationKey}
}

// Resolve one authenticated view once at stream admission, never from receipts
// or presence getters. Earlier/history sessions cannot mark a current tab live.
func observeHostedSessionView(ctx context.Context, owner, session string) func() {
	if owner == "" || session == "" {
		return func() {}
	}
	path := productConversationRegistryPath(owner)
	mu := productConversationRegistryMutex(path)
	mu.Lock()
	doc, err := defaultProductConversationRegistryStore().loadDocument(ctx, path)
	mu.Unlock()
	if err != nil {
		return func() {}
	}
	closes := []func(){}
	for _, record := range doc.Entries {
		if record.ProfileID == crewProfileID && record.SessionID == session && !hiddenFromTabStrip(record.ConversationKey) && !crewFunctionTabKey(record.ConversationKey) {
			closes = append(closes, observeHostedChatView(owner, hostedBindingForRecord(record)))
		}
	}
	return func() {
		for _, close := range closes {
			close()
		}
	}
}

// Import owns this origin bit; it is not guessed from a provider's label.
func (store productConversationRegistryStore) setImportedAgentName(ctx context.Context, owner, profile, key, label string) error {
	path := productConversationRegistryPath(owner)
	mu := productConversationRegistryMutex(path)
	mu.Lock()
	defer mu.Unlock()
	doc, err := store.loadDocument(ctx, path)
	if err != nil {
		return err
	}
	entry := productConversationRegistryEntryKey(profile, key)
	if _, exists := doc.Entries[entry]; !exists {
		return admissionRefused("imported chat no longer exists")
	}
	if doc.Agents == nil {
		doc.Agents = map[string]ProductAgentIdentity{}
	}
	identity := doc.Agents[entry]
	identity.Name, identity.GeneratedName = cleanAgentLabel(label), true
	doc.Agents[entry] = identity
	if err := store.writeDocument(ctx, path, doc); err != nil {
		return err
	}
	log.Printf("[AGENTBRIDGE] event=name_origin owner=%s chat=%s generated=true reason=automatic_name", owner, key)
	return nil
}
