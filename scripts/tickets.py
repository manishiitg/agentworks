#!/usr/bin/env python3
"""Platform tickets: one folder tree, like Brain (product / area / ticket), with generated indexes.

Layout: docs/bugs/pulse_platform/<product>/<area>/plat-NNN.md. Every ticket starts with the same header table
(State, Priority, Product, Area, Summary). Every folder has a generated index.md; the top one is the map, with the
newest tickets. There is no separate register (owner decision 2026-10-06, like Brain). Never edit an index by hand:
edit the ticket, then run `scripts/tickets.py index`.

  scripts/tickets.py new --product brain --area access --priority P2 "Title"   create the next ticket
  scripts/tickets.py index                                                     regenerate the indexes
  scripts/tickets.py check                                                     fail if anything is stale (CI)
  scripts/tickets.py migrate                                                   one-time conversion (2026-10-06)
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUGS = ROOT / 'docs' / 'bugs'
TICKETS = BUGS / 'pulse_platform'
REGISTER = BUGS / 'pulse_platform_issue_register.md'
GUIDE = TICKETS / 'README.md'

PRODUCTS = {
    'platform': 'Platform (shared runtime, sandbox, CLIs, chat, browser, integrations)',
    'goals': 'Goals (workflows: steps, plans, Pulse, evaluation)',
    'crew': 'Crew', 'code': 'Code', 'relays': 'Relays', 'vault': 'Vault', 'brain': 'Brain',
    'video-studio': 'Video Studio', 'sparkquill': 'SparkQuill', 'dominion': 'Dominion',
}
STATES = ('open', 'in progress', 'fixed on main', 'deployed', 'closed')
PRIORITIES = ('P0', 'P1', 'P2', 'P3', '-')
GOALS_AREAS = {'step-execution', 'plans-contracts', 'pulse-governance', 'evaluation', 'human-decisions'}
HEADER_FIELDS = ('State', 'Priority', 'Product', 'Area', 'Summary')
GENERATED = '<!-- Generated by scripts/tickets.py: do not edit. Edit the tickets, then run `scripts/tickets.py index`. -->'


def ticket_number(path):
    m = re.search(r'plat-(\d+)', path.name)
    return int(m.group(1)) if m else None


def ticket_files():
    return sorted(p for p in TICKETS.rglob('*.md') if p.name not in ('index.md', 'README.md') and ticket_number(p) is not None)


def read_header(text):
    """The standard header table: | Field | Value | rows right after the title."""
    fields = {}
    m = re.search(r'^\| Field \| Value \|\n\|---\|---\|\n((?:\|.*\|\n)+)', text, re.M)
    if m:
        for row in m.group(1).splitlines():
            cells = [c.strip() for c in row.strip('|').split('|', 1)]
            if len(cells) == 2 and cells[0] in HEADER_FIELDS:
                fields[cells[0]] = cells[1].replace('\\|', '|')
    return fields, m


def header_table(fields):
    rows = ''.join(f"| {k} | {str(fields.get(k, '')).replace('|', chr(92) + '|')} |\n" for k in HEADER_FIELDS)
    return '| Field | Value |\n|---|---|\n' + rows


def title_of(text, path):
    m = re.search(r'^# (.+)$', text, re.M)
    if m:
        return re.sub(r'^PLAT-\d+\s*[—:-]+\s*', '', m.group(1)).strip()
    return path.stem


def load():
    out = []
    for path in ticket_files():
        text = path.read_text()
        fields, _ = read_header(text)
        rel = path.relative_to(TICKETS)
        out.append({'path': path, 'rel': rel.as_posix(), 'n': ticket_number(path), 'title': title_of(text, path), **fields})
    return out


def rel_link(from_dir, target):
    return os.path.relpath(target, from_dir).replace(os.sep, '/')


def render_index(folder, tickets):
    """index.md for one folder: its subfolders (name and count only) and the tickets directly in it."""
    rel = folder.relative_to(TICKETS)
    depth = len(rel.parts)
    title = 'Platform tickets' if depth == 0 else ' / '.join(PRODUCTS.get(p, p) if i == 0 else p for i, p in enumerate(rel.parts))
    lines = [GENERATED, '', f'# {title}', '']
    if depth == 0:
        lines += ['How tickets work: [README](README.md). Each folder lists its own tickets.', '']
    subs = sorted(d for d in folder.iterdir() if d.is_dir())
    if subs:
        lines += ['| Folder | Tickets | Open |', '|---|---|---|']
        for d in subs:
            inside = [t for t in tickets if Path(t['path']).is_relative_to(d)]
            opened = sum(1 for t in inside if t.get('State') in ('open', 'in progress'))
            label = PRODUCTS.get(d.name, d.name) if depth == 0 else d.name
            lines.append(f"| [{label}]({d.name}/index.md) | {len(inside)} | {opened} |")
        lines.append('')
    if depth == 0:
        recent = sorted(tickets, key=lambda t: (-t['n'], t['rel']))[:40]
        lines += ['## Newest tickets', '', '| Ticket | Title | State | Priority | Folder |', '|---|---|---|---|---|']
        for t in recent:
            folder_rel = Path(t['rel']).parent.as_posix()
            lines.append(f"| [PLAT-{t['n']:03d}]({t['rel']}) | {t['title'].replace('|', chr(92) + '|')} | {t.get('State', '')} | {t.get('Priority', '')} | [{folder_rel}]({folder_rel}/index.md) |")
        lines.append('')
    here = sorted((t for t in tickets if Path(t['path']).parent == folder), key=lambda t: -t['n'])
    if here:
        lines += ['| Ticket | Title | State | Priority |', '|---|---|---|---|']
        for t in here:
            name = Path(t['path']).name
            lines.append(f"| [PLAT-{t['n']:03d}]({name}) | {t['title'].replace('|', chr(92) + '|')} | {t.get('State', '')} | {t.get('Priority', '')} |")
        lines.append('')
    return '\n'.join(lines)


def generated_files():
    tickets = load()
    files = {}
    for folder in [TICKETS] + sorted(d for d in TICKETS.rglob('*') if d.is_dir()):
        files[folder / 'index.md'] = render_index(folder, tickets)
    return files, tickets


def problems(tickets):
    out = []
    seen = {}
    for t in tickets:
        rel = t['rel']
        parts = Path(rel).parts
        if len(parts) != 3:
            out.append(f'{rel}: tickets live at <product>/<area>/plat-NNN.md')
            continue
        for field in HEADER_FIELDS[:4]:
            if not t.get(field):
                out.append(f'{rel}: header field {field} is missing')
        if t.get('State') and t['State'] not in STATES:
            out.append(f"{rel}: State must be one of {', '.join(STATES)}")
        if t.get('Priority') and t['Priority'] not in PRIORITIES:
            out.append(f"{rel}: Priority must be one of {', '.join(PRIORITIES)}")
        if t.get('Product') and (t['Product'] != parts[0] or t['Product'] not in PRODUCTS):
            out.append(f"{rel}: Product must match its folder and be one of {', '.join(PRODUCTS)}")
        if t.get('Area') and t['Area'] != parts[1]:
            out.append(f'{rel}: Area must match its folder')
        seen.setdefault(t['n'], []).append(rel)
    known = {339, 373, 496}  # numbers given twice before 2026-10-06; both tickets are kept
    for n, rels in seen.items():
        if len(rels) > 1 and n not in known:
            out.append(f'PLAT-{n:03d} is used by {len(rels)} tickets: {rels}')
    return out


def cmd_index(_):
    files, _ = generated_files()
    for path, text in files.items():
        path.write_text(text)
    print(f'wrote {len(files)} generated files')


def cmd_check(_):
    files, tickets = generated_files()
    issues = problems(tickets)
    stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
    stale_idx = [str(p.relative_to(ROOT)) for p in TICKETS.rglob('index.md') if p not in files]
    for msg in issues + [f'{s} is out of date: run scripts/tickets.py index' for s in stale + stale_idx]:
        print(msg, file=sys.stderr)
    if issues or stale or stale_idx:
        sys.exit(1)
    print(f'{len(tickets)} tickets, indexes current')


def cmd_new(args):
    if args.product not in PRODUCTS:
        sys.exit(f"product must be one of {', '.join(PRODUCTS)}")
    if not re.fullmatch(r'[a-z0-9-]+', args.area):
        sys.exit('area must be lower-case words joined by hyphens')
    n = max((ticket_number(p) or 0) for p in ticket_files()) + 1
    folder = TICKETS / args.product / args.area
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f'plat-{n:03d}.md'
    back = 'index.md'
    fields = {'State': 'open', 'Priority': args.priority, 'Product': args.product, 'Area': args.area, 'Summary': args.summary or ''}
    path.write_text(f"[← {args.product} / {args.area}]({back})\n\n# PLAT-{n:03d}: {args.title}\n\n{header_table(fields)}\n## What happened\n\n## Fix\n\n## Left\n")
    cmd_index(None)
    print(path.relative_to(ROOT))


