def classify_product(title, area):
    t = title.lower()
    rules = [('sparkquill', r'sparkquill'), ('dominion', r'dominion'), ('video-studio', r'video studio|video-studio'),
             ('brain', r'\bbrain\b|knowledge ?base|knowledgebase|\bkb\b'), ('vault', r'\bvault'),
             ('relays', r'\brelays?\b'), ('crew', r'\bcrews?\b'),
             ('code', r'\bcode (project|workspace|chat|product|tab|terminal|review)|\bcode product|private coding workspace')]
    for product, pattern in rules:
        if re.search(pattern, t):
            return product
    return 'goals' if area in GOALS_AREAS else 'platform'


def classify_state(text):
    t = text.lower()
    if re.search(r"won't fix|wontfix|not a platform issue|superseded|obsolete|\bremoved\b|\bclosed\b|no repository fix|third-party", t):
        return 'closed'
    if re.search(r'not (yet )?deployed|fixed on main|on main,|on main\.|implemented and tested locally|deployment is pending|deploy pending', t):
        return 'fixed on main'
    if re.search(r'\bdeployed\b|is live|green in rts|released|verified live|healthy in rts', t):
        return 'deployed'
    if re.search(r'in progress|being worked|partial', t):
        return 'in progress'
    if re.search(r'`implemented`|\bimplemented\b|\bfixed\b|\bresolved\b', t):
        return 'fixed on main'
    return 'open'


def first_sentence(text, limit=220):
    text = re.sub(r'\s+', ' ', re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', text)).strip()
    text = re.sub(r'^PLAT-\d+,?\s*(P[0-3],?\s*)?', '', text)
    m = re.match(r'(.+?[.!?])(\s|$)', text)
    s = (m.group(1) if m else text).strip()
    return s if len(s) <= limit else s[:limit - 1].rstrip() + '…'


def parse_register_blocks(reg):
    """Per-ticket prose keyed by ticket path, and the narrative sections that are not about one ticket."""
    blocks, narrative = {}, []
    parts = re.split(r'(?m)^(#{1,3} .+)$', reg)
    preamble = parts[0].strip()
    if preamble:
        narrative.append(('Notes kept from the old register', preamble))
    for i in range(1, len(parts), 2):
        heading, body = parts[i], parts[i + 1]
        m = re.match(r'#{1,3} (.+?)\s+—\s+PLAT-\d+', heading)
        link = re.search(r'\]\((pulse_platform/[^)]+\.md)\)', body)
        if m and link:
            blocks.setdefault(link.group(1), []).append((m.group(1).strip(), body.strip()))
        elif heading.strip('# ').strip() in ('Pulse Platform-Issue Register',) and not body.strip():
            continue
        else:
            narrative.append((heading.strip('# ').strip(), body.strip()))
    return blocks, narrative


def legacy_fields(text):
    f = {}
    for key, pattern in (('state', r'^\| (?:Ticket state|State|Status) \| `?([^`|]+)`? \|'), ('priority', r'(?:^\| Priority \| |\*\*Priority:\*\* ?)`?(P[0-3])')):
        m = re.search(pattern, text, re.M)
        if m:
            f[key] = m.group(1).strip()
    m = re.search(r'^\*\*State:\*\* (.+)$', text, re.M)
    if m:
        f['state'] = m.group(1)
    return f


def cmd_migrate(_):
    if any((TICKETS / p).is_dir() for p in PRODUCTS):
        sys.exit('already migrated')
    reg = REGISTER.read_text()
    blocks, narrative = parse_register_blocks(reg)
    plan = []
    for path in ticket_files():
        old_rel = path.relative_to(TICKETS).as_posix()
        area = path.parent.name
        text = path.read_text()
        reg_blocks = blocks.get(f'pulse_platform/{old_rel}', [])
        title = reg_blocks[0][0] if reg_blocks else title_of(text, path)
        reg_text = ' '.join(b for _, b in reg_blocks)
        legacy = legacy_fields(text)
        prio = re.search(r'\b(P[0-3])\b', reg_text[:400]) or re.search(r'\b(P[0-3])\b', legacy.get('priority', ''))
        state_src = reg_text[:600] if reg_text else legacy.get('state', '') + ' ' + text[:1500]
        product = classify_product(title, area)
        plan.append({'old': path, 'new': TICKETS / product / area / path.name, 'title': title, 'reg': reg_blocks,
                     'fields': {'State': classify_state(state_src), 'Priority': prio.group(1) if prio else '-',
                                'Product': product, 'Area': area, 'Summary': first_sentence(reg_blocks[0][1]) if reg_blocks else ''}})
    mapping = {p['old'].resolve(): p['new'] for p in plan}
    for p in plan:
        p['new'].parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(['git', 'mv', str(p['old']), str(p['new'])], check=True, cwd=ROOT)
    # Rewrite links everywhere in the repository's text files.
    old_to_new = {f"pulse_platform/{p['old'].relative_to(TICKETS).as_posix()}": f"pulse_platform/{p['new'].relative_to(TICKETS).as_posix()}" for p in plan}
    pattern = re.compile('|'.join(re.escape(k) for k in sorted(old_to_new, key=len, reverse=True)))
    tracked = subprocess.run(['git', 'ls-files'], capture_output=True, text=True, cwd=ROOT, check=True).stdout.split()
    for f in tracked:
        fp = ROOT / f
        if fp == REGISTER or fp.suffix not in ('.md', '.go', '.ts', '.tsx', '.py', '.yml', '.yaml', '.json', '.sh') or not fp.is_file():
            continue
        s = fp.read_text(errors='ignore')
        s2 = pattern.sub(lambda m: old_to_new[m.group(0)], s)
        if fp.parent != TICKETS and not fp.is_relative_to(TICKETS):
            s2 = s2.replace('pulse_platform_issue_register.md', 'pulse_platform/index.md')
        if s2 != s:
            fp.write_text(s2)
    # Inside tickets: relative links to other tickets and to the register.
    link = re.compile(r'\]\(((?:\.\./|\./)?[^)\s]*?\.md)(#[^)]*)?\)')
    for p in plan:
        new_dir, old_dir = p['new'].parent, p['old'].parent
        text = p['new'].read_text()

        def fix(m):
            target, anchor = m.group(1), m.group(2) or ''
            if target.startswith(('http', '/')):
                return m.group(0)
            old_abs = (old_dir / target).resolve()
            new_abs = mapping.get(old_abs, old_abs)
            if not new_abs.exists() and old_abs not in mapping:
                return m.group(0)
            return '](' + rel_link(new_dir, new_abs) + anchor + ')'
        text = re.sub(r'^\[←[^\]]*\]\([^)]*pulse_platform_issue_register\.md\)', f"[← {p['fields']['Product']} / {p['fields']['Area']}](index.md)", text, flags=re.M)
        text = text.replace('pulse_platform_issue_register.md', rel_link(new_dir, TICKETS / 'index.md'))
        text = link.sub(fix, text)
        lines = text.split('\n')
        at = next((i for i, l in enumerate(lines) if l.startswith('# ')), None)
        table = header_table(p['fields']).rstrip('\n').split('\n')
        if at is None:
            lines = [f"# PLAT-{ticket_number(p['new']):03d}: {p['title']}", ''] + table + [''] + lines
        else:
            lines = lines[:at + 1] + [''] + table + lines[at + 1:]
        text = '\n'.join(lines)
        if p['reg']:
            text = text.rstrip('\n') + '\n\n## Register notes\n\n' + '\n\n'.join(body for _, body in p['reg']) + '\n'
            text = link.sub(lambda m: m.group(0) if not m.group(1).startswith('pulse_platform/') else '](' + rel_link(new_dir, (BUGS / m.group(1)).resolve()) + (m.group(2) or '') + ')', text)
        p['new'].write_text(text)
    for d in sorted((d for d in TICKETS.iterdir() if d.is_dir() and d.name not in PRODUCTS), reverse=True):
        if not any(d.rglob('*')):
            d.rmdir()
    guide = ['# How platform tickets work', '',
             'Tickets live at `<product>/<area>/plat-NNN.md`, like Brain: product folders, area folders inside them, and a generated `index.md` in every folder. The top [index](index.md) is the map, with the newest tickets. There is no separate register.', '',
             'Every ticket starts with the same header table: State (open, in progress, fixed on main, deployed, closed), Priority (P0 to P3, or -), Product (its top folder), Area (its folder) and a one-line Summary. Edit the ticket, never an index.', '',
             '- New ticket: `scripts/tickets.py new --product <product> --area <area> --priority P2 "Title"` (takes the next number).',
             '- After editing tickets: `scripts/tickets.py index`. CI runs `scripts/tickets.py check`.', '',
             'Products: ' + ', '.join(f'`{k}` ({v})' for k, v in PRODUCTS.items()) + '.', '']
    for heading, body in narrative:
        if body:
            guide += [f'## {heading}', '', body, '']
    GUIDE.write_text('\n'.join(guide))
    subprocess.run(['git', 'rm', '-q', str(REGISTER)], check=True, cwd=ROOT)
    cmd_index(None)
    print(f'migrated {len(plan)} tickets')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='cmd', required=True)
    sub.add_parser('index')
    sub.add_parser('check')
    sub.add_parser('migrate')
    new = sub.add_parser('new')
    new.add_argument('--product', required=True)
    new.add_argument('--area', required=True)
    new.add_argument('--priority', default='-', choices=PRIORITIES)
    new.add_argument('--summary', default='')
    new.add_argument('title')
    args = parser.parse_args()
    {'index': cmd_index, 'check': cmd_check, 'migrate': cmd_migrate, 'new': cmd_new}[args.cmd](args)


if __name__ == '__main__':
    main()
