import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const output = new URL('../agent_go/internal/chatvisuals/slack-chat.cjs', root)
const built = await build({
  absWorkingDir: fileURLToPath(root), entryPoints: ['scripts/slack-chat-renderer.ts'],
  bundle: true, platform: 'node', format: 'cjs', target: 'node22', minify: true,
  legalComments: 'inline', write: false,
  banner: { js: '// Generated by frontend/scripts/build-slack-chat-renderer.mjs; pinned packages in frontend/package-lock.json.' },
})
const bytes = built.outputFiles[0].contents
if (process.argv.includes('--check')) {
  if (!Buffer.from(await readFile(output)).equals(Buffer.from(bytes))) throw new Error('Slack formatter is stale; regenerate with npm run build:slack-chat')
} else {
  await mkdir(new URL('./', output), { recursive: true })
  await writeFile(output, bytes)
}
console.log(`Slack formatter: ${bytes.length} bytes${process.argv.includes('--check') ? ', current' : ''}`)
